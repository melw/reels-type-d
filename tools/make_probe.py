"""make_probe.py - build the type probe FW96658T.BIN (called by build.ps1 -Probe). Identify only; never flashes.

  python tools/make_probe.py --out <FW96658T.BIN> [--dump <flash.bin>] [--pause 15] [--exclude NAME] [--badsig]

Known firmware (every row of pldr/bases.txt): start-up screen "TYPE X" + its name + its code. Unknown firmware:
"Unknown firmware" + its code, or a pause if no splash can be found. The screens are assembled at boot
(splashgen.py). Bootloader not Type D: own flash path. Shares pldr/pldr.c with the patch-loader (built without
-DPATCH). Needs Python packages numpy + Pillow (screens) and unicorn (emulator test).
"""
import argparse, os, sys
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pldr_common as C   # noqa: E402

BLD = os.path.join(C.ROOT, 'build', 'probe')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--dump', help='a 4 MB SPI flash dump of a Type D unit: run the emulator test')
    ap.add_argument('--pause', type=int, default=15)
    ap.add_argument('--exclude', action='append', default=[], help='leave a known image out (device test of "unknown")')
    ap.add_argument('--badsig', action='store_true', help='device test: as if the bootloader were not Type D')
    a = ap.parse_args()
    os.makedirs(BLD, exist_ok=True)

    bases = [b for b in C.load_bases(BLD) if b['name'] not in a.exclude]
    screens = [('Unknown firmware', '')] + [('TYPE ' + b['type'], b['label']) for b in bases]
    slots = [C.UNKNOWN_MAX] + [C.jpeg_len(b['img'], b['splash']) for b in bases]
    sg, sizes = C.make_screens(BLD, screens, slots)

    rows, specs = [], []
    for i, b in enumerate(bases):
        size, sm = C.fingerprint(b['img'])
        old = C.jpeg_len(b['img'], b['splash'])
        tp = os.path.join(BLD, 'expect-%s.rbn' % b['name'])
        open(tp, 'wb').write(C.expected_screen(sg, b['img'], i + 1, b['splash']))
        specs.append('%s=%s=%s' % (b['name'], b['path'], tp))
        rows.append((size, sm, i + 1, b['splash'], old))
        print('%-7s type %s  code %s  splash %#x (%d bytes)' % (b['name'], b['type'], C.code_of(b['img']), b['splash'], old))
    nl = chr(10)
    with open(os.path.join(BLD, 'bases.h'), 'w') as f:
        f.write('/* generated by make_probe.py */' + nl + '#define PAUSE_S %du%s#define NBASE %d%s' % (a.pause, nl, len(rows), nl))
        for decl, k, fmt in (('base_size', 0, '0x%xu'), ('base_sum', 1, '0x%08xu'), ('base_scr', 2, '%du'),
                             ('base_off', 3, '0x%xu'), ('base_len', 4, '%du')):
            f.write('static const u32 %s[NBASE] = {%s};' % (decl, ', '.join(fmt % r[k] for r in rows)) + nl)

    text, sym = C.compile_card(BLD, ['BADSIG'] if a.badsig else [])
    img = C.write_image(text, sym, a.out)
    print('probe %s: %d bytes, %d known images, sha256 %s' % (a.out, len(img), len(rows), C.sha(img)))

    if a.dump and (a.badsig or a.exclude):
        print('emulator test skipped for a device-test variant')
    elif a.dump:
        own = [b['name'] for b in bases if b['name'] in ('fw292', 'stockD', '0dan0A')]
        print(C.run([sys.executable, os.path.join(C.ROOT, 'tools', 'emu_pldr.py'), a.out, a.dump,
                     'halt=%x' % sym['halt'], 'sg=' + os.path.join(BLD, 'splashgen.pkl'),
                     'unknown=%s=%x' % (bases[-1]['path'], bases[-1]['splash']), 'own=' + ','.join(own)] + specs).strip())
    else:
        print('emulator test skipped (no --dump)')


if __name__ == '__main__':
    main()
