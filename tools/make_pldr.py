"""make_pldr.py - build the patch-loader FW96658T.BIN for a build (called by build.ps1 -Card).

  python tools/make_pldr.py --target-rbn build/vd-osd.rbn --target-bin out/build-N/FWDV280.BIN
                            --out out/build-N/FW96658T.BIN --build N [--dump <flash_dump.bin>]

The patch-loader runs from the SD card (the bootloader runs FW96658T.BIN from RAM and never writes flash). It reads
the unit's installed firmware from flash, recognises it (size + 32-bit word sum) as one of the bases in
pldr/bases.txt with use = patch, patches it into the target in RAM and boots it. The target itself boots as it
is. Anything else boots unpatched, with "Unknown firmware" and its code on the start-up screen.
The file contains only our code and the target's words at the patched places, no complete Kodak firmware.

Steps: bases (pldr_common) -> per-base runs of differing words + one shared pool of target words -> the unknown
screen -> build/pldr/bases.h + splashgen.h -> compile pldr/ with -DPATCH -> raw image -> optional emulator test
against a flash dump (tools/emu_pldr.py, needs `pip install unicorn`).
"""
import argparse, bisect, os, struct, sys
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pldr_common as C   # noqa: E402

BLD = os.path.join(C.ROOT, 'build', 'pldr')
PAUSE_S = 15
OWN_TESTS = ('stockD', 'vdD', 'fw292')     # also tested through the own flash path (as if another bootloader)


def patch_tables(bases, tgt):
    n = len(tgt) // 4
    T = struct.unpack('<%dI' % n, tgt)
    per = []
    for b in bases:
        if len(b['img']) != len(tgt):
            C.die('base %s: size %d differs from the target (%d)' % (b['name'], len(b['img']), len(tgt)))
        B = struct.unpack('<%dI' % n, b['img'])
        d = [B[i] != T[i] for i in range(n)]
        runs, i = [], 0
        while i < n:                                 # runs of differing words, 1-word gaps bridged
            if d[i]:
                j = i + 1
                while j < n and (d[j] or (j + 1 < n and d[j + 1])):
                    j += 1
                runs.append((i, j - i))
                i = j
            else:
                i += 1
        per.append((b['name'], C.fingerprint(b['img'])[1], runs, B))
    if C.fingerprint(tgt) in [C.fingerprint(b['img']) for b in bases]:
        C.die('the target has the fingerprint of a base (target == an installed release?)')

    merged = []                                      # shared pool: target words over the union of all runs
    for s0, e0 in sorted((s0, s0 + l) for _, _, rr, _ in per for s0, l in rr):
        if merged and s0 <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], e0)
        else:
            merged.append([s0, e0])
    pool, pstart = [], []
    for s0, e0 in merged:
        pstart.append(len(pool))
        pool.extend(T[s0:e0])
    mstarts = [m[0] for m in merged]

    def pool_idx(w):
        k = bisect.bisect_right(mstarts, w) - 1
        return pstart[k] + w - merged[k][0]

    tab = {'size': [], 'sum': [], 'first': [], 'nrun': [], 'off': [], 'len': [], 'pool_i': []}
    for name, sm, rr, B in per:
        tab['size'].append(len(tgt)); tab['sum'].append(sm); tab['first'].append(len(tab['off'])); tab['nrun'].append(len(rr))
        img = list(B)
        for s0, l in rr:
            p0 = pool_idx(s0)
            tab['off'].append(s0 * 4); tab['len'].append(l); tab['pool_i'].append(p0)
            img[s0:s0 + l] = pool[p0:p0 + l]
        if tuple(img) != T:                          # self-check: the runs reproduce the target exactly
            C.die('base %s: patch runs do not reproduce the target' % name)
        print('base %-7s sum %08x: %4d runs, %6d words' % (name, sm, len(rr), sum(l for _, l in rr)))
    tab['size'].append(len(tgt)); tab['sum'].append(C.fingerprint(tgt)[1])   # the target itself: known, 0 runs
    tab['first'].append(len(tab['off'])); tab['nrun'].append(0)
    return tab, pool


def write_header(path, tab, pool, tgt, names):
    nl = chr(10)
    with open(path, 'w') as f:
        f.write('/* generated by tools/make_pldr.py: target %s; bases %s + the target */' % (C.sha(tgt)[:16], ', '.join(names)) + nl)
        f.write('#define PAUSE_S %du%s#define NBASE %d%s#define NRUN %d%s#define NPOOL %d%s'
                % (PAUSE_S, nl, len(tab['sum']), nl, len(tab['off']), nl, len(pool), nl))
        for decl, vals in (('base_size[NBASE]', ['0x%xu' % x for x in tab['size']]),
                           ('base_sum[NBASE]', ['0x%08xu' % x for x in tab['sum']]),
                           ('base_first[NBASE]', [str(x) for x in tab['first']]),
                           ('base_nrun[NBASE]', [str(x) for x in tab['nrun']]),
                           ('run_off[NRUN]', ['0x%x' % x for x in tab['off']]),
                           ('run_len[NRUN]', [str(x) for x in tab['len']]),
                           ('run_pool[NRUN]', [str(x) for x in tab['pool_i']]),
                           ('pool[NPOOL]', ['0x%08x' % x for x in pool])):
            f.write('static const u32 %s = {%s};' % (decl, ', '.join(vals)) + nl)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--target-rbn', required=True)
    ap.add_argument('--target-bin', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--build', required=True, help='build number, shown on the unknown-firmware screen')
    ap.add_argument('--dump', help='a 4 MB SPI flash dump of a Type D unit: run the emulator test')
    a = ap.parse_args()
    os.makedirs(BLD, exist_ok=True)
    tgt = open(a.target_rbn, 'rb').read()
    if struct.unpack_from('<I', tgt, 0x68)[0] != len(tgt):
        C.die('target: size word at 0x68 does not match')

    bases = C.load_bases(BLD, 'patch')
    tab, pool = patch_tables(bases, tgt)
    write_header(os.path.join(BLD, 'bases.h'), tab, pool, tgt, [b['name'] for b in bases])
    sg, _ = C.make_screens(BLD, [('Unknown firmware', '')], [C.UNKNOWN_MAX],
                           heading='FW %s patch-loader' % a.build, note='Not patched.')
    text, sym = C.compile_card(BLD, ['PATCH'])
    img = C.write_image(text, sym, a.out)
    print('patch-loader %s: %d bytes, %d bases + the target, %d runs, pool %d words'
          % (a.out, len(img), len(bases), len(tab['off']), len(pool)))

    if a.dump:
        tp = os.path.join(BLD, 'target.rbn')
        open(tp, 'wb').write(tgt)
        cases = ['%s=%s=%s' % (b['name'], b['path'], tp) for b in bases] + ['target=%s=%s' % (a.target_bin, tp)]
        own = [b['name'] for b in bases if b['name'] in OWN_TESTS]
        print(C.run([sys.executable, os.path.join(C.ROOT, 'tools', 'emu_pldr.py'), a.out, a.dump,
                     'halt=%x' % sym['halt'], 'sg=' + os.path.join(BLD, 'splashgen.pkl'),
                     'unknown=%s=%x' % (bases[-1]['path'], bases[-1]['splash']), 'own=' + ','.join(own)] + cases).strip())
    else:
        print('emulator test skipped (no -Dump)')
    print('PLDR_BASES=' + ','.join(b['name'] for b in bases))


if __name__ == '__main__':
    main()
